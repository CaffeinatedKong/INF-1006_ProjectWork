# GPIO Pin where the touch sensor is connected
TOUCH_SENSOR_PIN = 17  # Replace with the GPIO pin you are using
TRANSMITTER_SENSOR_PIN = 27 
DHT_sensor = adafruit_dht.DHT11(board.D26) 

# Set up the GPIO pin as an input
GPIO.setup(TOUCH_SENSOR_PIN, GPIO.IN)
pi.set_mode(TRANSMITTER_SENSOR_PIN, pigpio.INPUT)

# Function to transmit the ON signal
def transmit_on_signal():
    print("Transmitting ON signal...")
    transmitting = True  # Set flag to indicate transmission is happening
    
    for tick in on_signal:
        pi.write(TRANSMITTER_SENSOR_PIN, 1)  # Turn on the IR LED
        time.sleep(tick / 1000000.0)  # Convert microseconds to seconds
        pi.write(TRANSMITTER_SENSOR_PIN, 0)  # Turn off the IR LED
        time.sleep(0.0005)  # Small gap between pulses
    
    transmitting = False  # Reset flag once transmission is done
    print("ON signal transmission complete.")

# Function to transmit the OFF signal
def transmit_off_signal():
    
    transmitting = True  # Set flag to True (start transmitting)
    print("Transmitting OFF signal...")
    
    for tick in off_signal:
        pi.write(TRANSMITTER_SENSOR_PIN, 1)  # Turn on the IR LED
        time.sleep(tick / 1000000.0)  # Convert microseconds to seconds
        pi.write(TRANSMITTER_SENSOR_PIN, 0)  # Turn off the IR LED
        time.sleep(0.0005)  # Small gap between pulses
    
    transmitting = False  # Reset the flag to False once transmission is complete
    print("OFF signal transmission complete.")
    

# This will be called when the client connects to the broker
def on_connect(client, userdata, flags, rc):
    print("Connected to MQTT Broker with result code " + str(rc))
    # Subscribe to the command topic (aircon/controller)
    client.subscribe(mqtt_topic_command)

# This will be called when a message is received on the subscribed topic
def on_message(client, userdata, msg):
    print(f"Received MQTT message on {msg.topic}: {msg.payload.decode()}")
    if msg.topic == mqtt_topic_command:
        if msg.payload.decode() == "on":
            # Call the method to on aircon
            print("On aircon...")
            threading.Thread(target=transmit_on_signal).start()
            time.sleep(2)
            print("Aircon On")
            pi.write(TRANSMITTER_SENSOR_PIN, 0)
            # After dispensing, send a status update back
            client.publish(mqtt_topic_status, "Aircon on successfully", qos=1)
        elif msg.payload.decode() == "off":
            # Simulate aircon off
            print("Off aircon")
            threading.Thread(target=transmit_off_signal).start()
            time.sleep(2)
            print("Aircon off")
            pi.write(TRANSMITTER_SENSOR_PIN, 0)
            # After dispensing, send a status update back
            client.publish(mqtt_topic_status, "Aircon off", qos=1)

def detect_touch_and_control_temperature(client):
    try:
        while True:
            # Read the temperature and humidity
            temperature, humidity = read_temperature_and_humidity()

            if temperature is not None:
                # Control aircon based on temperature
                if temperature > 30:
                    # If temperature is above 30, turn on the aircon
                    print("Temperature above 30°C, turning on the aircon...")
                    threading.Thread(target=transmit_on_signal).start()
                    time.sleep(2)
                    pi.write(TRANSMITTER_SENSOR_PIN, 0)
                    print("Aircon On")
                elif temperature < 26:
                    # If temperature is below 26, turn off the aircon
                    print("Temperature below 26°C, turning off the aircon...")
                    threading.Thread(target=transmit_off_signal).start()
                    time.sleep(2)
                    pi.write(TRANSMITTER_SENSOR_PIN, 0)
                    print("Aircon off")

            # Check for touch sensor input
            if GPIO.input(TOUCH_SENSOR_PIN) == GPIO.HIGH:
                print("Touch detected!")
                # Send MQTT message to the caretaker (via touch/help topic)
                client.publish(mqtt_topic_touch, "Help requested!", qos=1)
                time.sleep(2)  # Add a delay to avoid multiple messages

            time.sleep(5)  # Polling rate for both touch and temperature checks

    except KeyboardInterrupt:
        print("Program interrupted.")
    finally:
        GPIO.cleanup()

def read_temperature_and_humidity():
    try:
        # Retry mechanism in case of checksum failure
        for _ in range(5):  # Retry up to 5 times
            temperature_c = DHT_sensor.temperature
            humidity = DHT_sensor.humidity
            
            if temperature_c is not None and humidity is not None:
                print(f"Temp: {temperature_c:.1f}°C  Humidity: {humidity:.1f}%")
                return temperature_c, humidity
            else:
                print("Sensor failure. Retrying...")
            time.sleep(1)  # Delay before retrying
        
        # If all retries fail
        print("Sensor failure after 5 retries. Check wiring.")
        return None, None
    except Exception as e:
        print(f"Error reading sensor data: {e}")
        return None, None

